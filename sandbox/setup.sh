self_sha="$(sha256sum "${BASH_SOURCE[0]}" | cut -d' ' -f1)"

fetch() {  # fetch <url> <dest> <sha256>: three attempts, then fail the bake
  local url="$1" dest="$2" want="$3" attempt
  for attempt in 1 2 3; do
    if curl -fsSL --connect-timeout 15 --max-time 300 "$url" -o "$dest" \
      && printf '%s  %s\n' "$want" "$dest" | sha256sum -c --status -; then
      return 0
    fi
    echo "download or checksum failed: $url (attempt $attempt of 3)" >&2
    sleep 3
  done
  return 1
}

install_system() {
  export DEBIAN_FRONTEND=noninteractive
  apt-get -o Acquire::Retries=5 update
  # Chrome Headless Shell's shared libraries, ffmpeg, fontconfig, and the tools Deep Agents'
  # file tools and the workspace gates shell out to (python3, ripgrep, jq).
  apt-get -o Acquire::Retries=5 install -y --no-install-recommends \
    ca-certificates curl unzip xz-utils procps python3 ripgrep jq woff2 \
    ffmpeg fontconfig fonts-liberation fonts-noto-color-emoji \
    libnss3 libnspr4 libatk1.0-0 libatk-bridge2.0-0 libcups2 libdrm2 libxkbcommon0 \
    libxcomposite1 libxdamage1 libxfixes3 libxrandr2 libgbm1 libasound2 libpango-1.0-0 \
    libcairo2 libdbus-1-3 libexpat1 libx11-6 libxcb1 libxext6
  rm -rf /var/lib/apt/lists/*
}

install_fonts() {
  local entry name sha path
  mkdir -p "$FONT_DIR" /workspace/fonts
  for entry in "${FONTS[@]}"; do
    IFS='|' read -r name sha path <<<"$entry"
    fetch "https://raw.githubusercontent.com/google/fonts/${GOOGLE_FONTS_REV}/${path}" \
      "$FONT_DIR/$name" "$sha"
  done
  # Brand and licensed fonts are staged into /workspace/fonts at run time.
  cat >/etc/fonts/conf.d/99-design-agent.conf <<'XML'
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<fontconfig>
  <dir>/usr/local/share/fonts/design-agent</dir>
  <dir>/workspace/fonts</dir>
</fontconfig>
XML
  fc-cache -f
}

install_d2() {
  local tmp
  tmp="$(mktemp -d)"
  fetch "https://github.com/d2lang/d2/releases/download/v${D2_VERSION}/d2-v${D2_VERSION}-linux-${ARCH}.tar.gz" \
    "$tmp/d2.tgz" "$D2_SHA256"
  tar -xzf "$tmp/d2.tgz" -C "$tmp"
  install -m 0755 "$tmp/d2-v${D2_VERSION}/bin/d2" /usr/local/bin/d2
  rm -rf "$tmp"
}

install_chrome() {
  local tmp
  tmp="$(mktemp -d)"
  fetch "$CHROME_URL" "$tmp/chs.zip" "$CHROME_ZIP_SHA256"
  rm -rf "$CHROME_DIR"
  mkdir -p "$CHROME_DIR"
  unzip -q "$tmp/chs.zip" -d "$CHROME_DIR"
  rm -rf "$tmp"
  ln -sfn "$CHROME_DIR/$CHROME_BINARY" /usr/local/bin/chrome-headless-shell
  if ldd /usr/local/bin/chrome-headless-shell | grep -q 'not found'; then
    ldd /usr/local/bin/chrome-headless-shell | grep 'not found' >&2
    return 1
  fi
}

install_render_toolchain() {
  rm -rf "$RENDER_DIR"
  mkdir -p "$RENDER_DIR"
  printf '%s' "$RENDER_LOCK_B64" | base64 -d | tar -xz -C "$RENDER_DIR"
  # npm ci verifies every package against the lockfile's sha512 integrity. No package in the
  # lock needs an install script: sharp and esbuild ship prebuilt platform packages.
  (cd "$RENDER_DIR" && npm ci --ignore-scripts --no-audit --no-fund --omit=dev)
  # One wrapper so every caller (the agent's shell, render jobs, the probe) gets the pinned
  # browser and no telemetry, update checks or skill installs, whatever its environment.
  cat >/usr/local/bin/hyperframes <<SH
#!/usr/bin/env bash
export HYPERFRAMES_BROWSER_PATH=/usr/local/bin/chrome-headless-shell
export HYPERFRAMES_NO_TELEMETRY=1 DO_NOT_TRACK=1 HYPERFRAMES_NO_UPDATE_CHECK=1
export HYPERFRAMES_NO_AUTO_INSTALL=1 HYPERFRAMES_SKIP_SKILLS=1 PUPPETEER_SKIP_DOWNLOAD=1
exec "$RENDER_DIR/node_modules/.bin/hyperframes" "\$@"
SH
  chmod 0755 /usr/local/bin/hyperframes
}

write_probe() {
  mkdir -p "$RECIPE_ROOT/probe"
  cat >"$RECIPE_ROOT/probe/composition.html" <<'HTML'
<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="gsap.min.js"></script>
    <style>
      html, body { margin: 0; width: 1920px; height: 1080px; overflow: hidden; background: #101418; }
      #root { width: 100%; height: 100%; display: flex; align-items: center; justify-content: center; }
      #title { color: #f6f1e7; font: 600 120px "Inter", sans-serif; letter-spacing: -0.03em; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="2" data-width="1920" data-height="1080">
      <h1 id="title" class="clip" data-start="0" data-duration="2" data-track-index="0">Probe</h1>
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
      tl.fromTo("#title", { opacity: 0.4, y: 40 }, { opacity: 1, y: 0, duration: 1.5 }, 0);
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
HTML
  cat >"$RECIPE_ROOT/probe/page.html" <<'HTML'
<!doctype html>
<html><body style="margin:0;background:#f6f1e7">
<p style="font:600 64px 'Fraunces';margin:40px">Fraunces</p>
<p style="font:400 40px 'Inter';margin:40px">Inter</p>
<p style="font:500 32px 'IBM Plex Mono';margin:40px">IBM Plex Mono</p>
</body></html>
HTML
  cat >"$RECIPE_ROOT/probe/probe.sh" <<'SH'
#!/usr/bin/env bash
# Proves the computer can do its job: fonts resolve, the browser screenshots, HyperFrames lints
# and renders, ffprobe confirms the output. Exit 1 on any failure.
set -euo pipefail
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
probe_dir=/opt/design-agent/probe

for family in "Inter" "IBM Plex Mono" "Fira Code" "Fraunces"; do
  got="$(fc-match -f '%{family[0]}' "$family")"
  [ "$got" = "$family" ] || { echo "font did not resolve: $family -> $got" >&2; exit 1; }
done

chrome-headless-shell --no-sandbox --disable-gpu --hide-scrollbars --window-size=800,600 \
  --screenshot="$work/page.png" "file://$probe_dir/page.html" >/dev/null 2>&1
[ "$(head -c 8 "$work/page.png" | od -An -tx1 | tr -d ' \n')" = "89504e470d0a1a0a" ] \
  || { echo "browser screenshot failed" >&2; exit 1; }

mkdir -p "$work/film"
cp "$probe_dir/composition.html" "$work/film/index.html"
cp /opt/design-agent/render/node_modules/gsap/dist/gsap.min.js "$work/film/gsap.min.js"
hyperframes lint "$work/film" >/dev/null
hyperframes render "$work/film" --quality draft --fps 30 --output "$work/probe.mp4" --quiet >/dev/null
duration="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$work/probe.mp4")"
size="$(ffprobe -v error -select_streams v:0 -show_entries stream=width,height -of csv=p=0:s=x "$work/probe.mp4")"
python3 - "$duration" "$size" <<'PY'
import sys
duration, size = float(sys.argv[1]), sys.argv[2]
assert abs(duration - 2.0) <= 1 / 30 + 1e-6, f"duration {duration}"
assert size == "1920x1080", f"size {size}"
PY

printf 'shape: rectangle\na -> b\n' >"$work/probe.d2"
d2 --layout=dagre "$work/probe.d2" "$work/probe.svg" >/dev/null 2>&1
grep -q '<svg' "$work/probe.svg"

node -e "require('/opt/design-agent/render/node_modules/sharp'); require('/opt/design-agent/render/node_modules/echarts')"

echo "probe ok: node $(node --version), hyperframes $(hyperframes --version), d2 $(d2 --version)," \
  "$(ffmpeg -version | head -1 | cut -d' ' -f1-3), $(chrome-headless-shell --version 2>/dev/null | head -1)"
SH
  chmod 0755 "$RECIPE_ROOT/probe/probe.sh"
}

